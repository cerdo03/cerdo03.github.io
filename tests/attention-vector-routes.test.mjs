import {test} from 'node:test';
import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
test('vector routing keeps context, layer and head origins separate',async()=>{
 const file=new URL('../labs/attention/vector-routes.js',import.meta.url);
 assert.ok(existsSync(file),'inline vector route diagram is missing');
 const {routeState}=await import(file);
 const first=routeState(1,1,2);
 assert.deepEqual(first.inputs.map(row=>row.context),[[0],[1],[2]]);
 const later=routeState(2,1,2);
 assert.deepEqual(later.inputs.map(row=>row.context),[[0],[0,1],[0,1,2]]);
 assert.equal(later.inputs[1].sourceLayer,1);
 assert.deepEqual(later.allowed,[0,1,2]);
 assert.ok(later.rows.every(row=>row.layer===2&&row.head===1));
 const other=routeState(2,2,2);
 assert.deepEqual(other.inputs,later.inputs);
 assert.ok(other.rows.every(row=>row.head===2));
 assert.deepEqual(routeState(2,1,1).allowed,[0,1]);
 assert.deepEqual(routeState(2,1,1).rows,later.rows);
});
test('network connections cross adjacent layers and never read a later token',async()=>{
 const module=await import('../labs/attention/vector-routes.js');
 assert.equal(typeof module.networkEdges,'function');
 const edges=module.networkEdges();
 assert.equal(edges.length,12);
 assert.ok(edges.every(edge=>edge.toLayer===edge.fromLayer+1&&edge.fromPosition<=edge.toPosition));
 assert.deepEqual(edges.filter(edge=>edge.toLayer===2&&edge.toPosition===1).map(edge=>edge.fromPosition),[0,1]);
});
test('operation stepping separates projection products, sums, scaling and normalization',async()=>{
 const {routeOperation}=await import('../labs/attention/vector-routes.js');
 assert.equal(typeof routeOperation,'function');
 const operations=Array.from({length:12},(_,i)=>routeOperation(i));
 assert.deepEqual(operations.map(o=>o.phase),[0,1,1,1,2,2,2,3,3,4,4,4]);
 assert.match(operations[1].formula,/×/);
 assert.match(operations[2].formula,/×/);
 assert.match(operations[3].formula,/Σ/);
 assert.match(operations[4].formula,/Σ/);
 assert.match(operations[5].formula,/√/);
 assert.match(operations[6].formula,/exp/);
 assert.match(operations[7].formula,/×/);
 assert.match(operations[8].formula,/Σ/);
 assert.match(operations[9].why,/No addition/);
 assert.ok(operations.every(o=>o.title&&o.why&&o.formula));
 assert.throws(()=>routeOperation(12),RangeError);
});
